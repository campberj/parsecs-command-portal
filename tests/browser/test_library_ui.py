"""Unit library and army lists: filters, search, unit modal, list building, print, Quick battle hand-off, persistence, backups."""
from playwright.sync_api import sync_playwright
from common import Checks, launch, boot, import_pack, no_hscroll, out

chk = Checks('library UI')
with sync_playwright() as pw:
    ctx, pg, errs, _ = launch(pw, width=1366)
    pg.on('dialog', lambda d: d.accept('Droid Front' if 'Name' in d.message else '400'))
    boot(pg); import_pack(pg)
    pg.click('#tab-library'); pg.wait_for_timeout(200)
    total = pg.evaluate("document.querySelectorAll('.libcard').length"); chk(f'library lists units ({total})', total > 30)
    pg.select_option('#lib-fac', 'f-cis'); pg.wait_for_timeout(150); pg.select_option('#lib-troop', 'vehicle'); pg.wait_for_timeout(150)
    veh = pg.evaluate("document.querySelectorAll('.libcard').length"); chk(f'faction + type filter ({veh})', 0 < veh < total)
    pg.fill('#lib-q', 'tank'); pg.press('#lib-q', 'Enter'); pg.wait_for_timeout(150)
    names = pg.evaluate("[...document.querySelectorAll('.libcard b')].map(b=>b.textContent)")
    chk('search finds tanks', len(names) > 0 and all('tank' in n.lower() or 'aat' in n.lower() or 'persuader' in n.lower() for n in names))
    pg.select_option('#lib-troop', ''); pg.fill('#lib-q', ''); pg.press('#lib-q', 'Enter'); pg.wait_for_timeout(150)
    pg.click('[data-act="listnew"]'); pg.wait_for_timeout(200)
    chk('new list created', pg.evaluate("LISTS.length") == 1 and pg.evaluate("LISTS[0].name") == 'Droid Front')
    pg.click('[data-act="libview"][data-id="t-cis-grievous"]'); pg.wait_for_timeout(200)
    chk('unit modal with weapons', pg.query_selector('.modal') is not None and 'Four lightsabers' in pg.inner_text('.modal'))
    pg.screenshot(path=out('lib_modal.png'))
    pg.click('.modal [data-act="libadd"]'); pg.wait_for_timeout(150)
    for tid in ['t-cis-b1', 't-cis-b1', 't-cis-b2', 't-cis-aat']:
        pg.click(f'[data-act="libadd"][data-id="{tid}"]'); pg.wait_for_timeout(100)
    chk('list entries merge counts', pg.evaluate("LISTS[0].entries.length") == 4 and pg.evaluate("LISTS[0].entries.find(e=>e.tpl.id==='t-cis-b1').count") == 2)
    pg.screenshot(path=out('lib_page.png'))
    pg.evaluate("window.print=()=>{}"); pg.click('[data-act="listprint"]'); pg.wait_for_timeout(200)
    chk('list prints on Letter sheets', pg.evaluate("document.querySelectorAll('#printroot .sheet').length") >= 1 and pg.evaluate("document.querySelectorAll('#printroot .icard').length") >= 5)
    pg.click('[data-act="listquick"][data-k="player"]'); pg.wait_for_timeout(200)
    chk('Quick battle opens with the list chosen', pg.evaluate("S.ui.tab") == 'quick' and 'Droid Front' in pg.eval_on_selector('#qb-plist', 'e=>e.selectedOptions[0].textContent'))
    pg.select_option('#qb-tier', '3'); pg.click('form[data-form="quick"] button[type=submit]'); pg.wait_for_timeout(400)
    chk('battle uses the list and its points', pg.evaluate("S.quick.player.name") == 'Droid Front' and pg.evaluate("S.quick.units.length") == 5)
    pg.reload(); pg.wait_for_function('typeof S !== "undefined" && S && S.map'); pg.wait_for_timeout(400)
    chk('lists survive reload', pg.evaluate("LISTS.length") == 1)
    chk('backup carries lists', pg.evaluate("backupBundle('test').then(b=>b.lists.length)") == 1)
    pg.set_viewport_size({'width': 390, 'height': 844}); pg.click('#tab-library'); pg.wait_for_timeout(200)
    chk('phone: no horizontal scroll', no_hscroll(pg))
    chk('no page errors', not errs)
    ctx.close()
chk.finish()
