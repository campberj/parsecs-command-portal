"""BLKOUT pack through the UI: import, factions panel, library, Duster detail, quick battle and printed cards."""
from playwright.sync_api import sync_playwright
from common import Checks, launch, boot, import_pack, no_hscroll, out, PACKS

chk = Checks('BLKOUT UI')
with sync_playwright() as pw:
    ctx, pg, errs, _ = launch(pw, width=1366)
    boot(pg)
    pg.click('#tab-forces'); pg.click('[data-act="importopen"]'); pg.set_input_files('#imp-ufile', str(PACKS / 'blkout-pack.json')); pg.wait_for_timeout(300)
    chk('import preview lists the new units', pg.inner_text('#modal').count('Duster') >= 4)
    pg.click('form[data-form="importapply"] button[type=submit]'); pg.wait_for_timeout(200)
    chk('three blocs imported', pg.evaluate("['f-blk-authority','f-blk-manticor','f-blk-boone'].every(id => S.armory.factions.some(f => f.id === id))"))
    pg.click('#tab-armory'); pg.click('[data-act="atab"][data-k="factions"]'); pg.wait_for_timeout(200)
    v = pg.inner_text('#view').upper(); chk('factions panel shows the blocs', 'THE AUTHORITY (BLKOUT)' in v and 'MANTICOR BORZ GROUP' in v and 'TASK FORCE BOONE' in v)
    pg.click('#tab-library'); pg.wait_for_timeout(200)
    pg.select_option('#lib-fac', 'f-blk-manticor'); pg.wait_for_timeout(150)
    chk('library filters to Manticor', pg.evaluate("document.querySelectorAll('.libcard').length") == 14)
    pg.click('[data-act="libview"][data-id="t-blk-mbg-duster-topor"]'); pg.wait_for_timeout(200)
    m = pg.inner_text('.modal'); chk('Duster detail: weapons and Mobility rule', '30mm autocannon' in m and 'Mobility 3' in m)
    pg.screenshot(path=out('blkout_duster.png'))
    pg.keyboard.press('Escape')
    pg.click('#tab-quick'); pg.select_option('#qb-tier', '3'); pg.select_option('#qb-player', 'f-blk-boone'); pg.select_option('#qb-opp', 'f-blk-authority'); pg.fill('#qb-seed', 'BLK')
    pg.click('form[data-form="quick"] button[type=submit]'); pg.wait_for_timeout(400)
    chk('quick battle Boone vs Authority', pg.evaluate("S.quick.player.faction === 'f-blk-boone' && S.quick.opp.faction === 'f-blk-authority'"))
    pg.evaluate("window.print = () => {}"); pg.select_option('#qb-size', '46'); pg.select_option('#qb-paper', 'letter'); pg.wait_for_timeout(100)
    pg.click('[data-act="qprint"]'); pg.wait_for_timeout(250)
    cards = pg.evaluate("document.querySelectorAll('#printroot .icard').length"); chk(f'battle pack prints ({cards} cards)', cards > 4)
    for size in ['35', '46']:
        pg.select_option('#qb-size', size); pg.wait_for_timeout(100); pg.click('[data-act="qprint"]'); pg.wait_for_timeout(250)
        pg.emulate_media(media='print')
        over = pg.evaluate("[...document.querySelectorAll('#printroot .icard')].filter(c => c.scrollHeight > c.clientHeight + 2).map(c => c.querySelector('h5') && c.querySelector('h5').textContent)")
        chk(f'{size} cards: none overflow ' + ', '.join(over), not over)
        refs = pg.evaluate("[...document.querySelectorAll('#printroot .icard h5')].filter(h => /Rules in force/i.test(h.textContent)).length")
        chk(f'{size} cards: reference split over {refs} card(s)', refs >= 1)
        pg.pdf(path=out(f'blkout_pack_{size}.pdf'), prefer_css_page_size=True, print_background=True); pg.emulate_media(media='screen')
    pg.set_viewport_size({'width': 390, 'height': 844}); pg.click('#tab-library'); pg.wait_for_timeout(200)
    chk('phone: no horizontal scroll', no_hscroll(pg))
    chk('no page errors', not errs)
    ctx.close()
chk.finish()
